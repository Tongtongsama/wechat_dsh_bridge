"""判断一条消息"说完了没有"。

聊天里常见的习惯是把一句话拆成几段发：
    差不多像是（发送）
    这个样子（发送）
如果每条都立刻回，就会变成鸡同鸭讲——它回的是半句话。

这里用一组启发式规则判断"看起来还没说完"：
  · 结尾是逗号、顿号、破折号这类"接续"标点
  · 结尾是"和/跟/因为/所以/然后/但是/如果/的话"这类明显的连接词
  · 有没闭合的括号或引号
  · 很短、且没有句末语气词（吗/呢/吧/啊/了/…）

规则只用来**延长等待**，不决定要不要回。判错了代价很小——多等几秒而已。
"""
from __future__ import annotations

# 结尾出现这些，说明后面还有话
_CONTINUATIONS = (
    "，", ",", "、", "；", ";", "：", ":", "——", "—", "…", "...",
    "和", "跟", "与", "因为", "所以", "但是", "但", "然后", "就是",
    "如果", "的话", "而且", "或者", "还是", "以及", "不过", "只是",
    "虽然", "既然", "要是", "等于", "比如", "像", "就是说",
)

# 结尾出现这些，基本可以认为说完了
_ENDINGS = (
    "。", "！", "!", "？", "?", "…", "~", "～",
    "吗", "呢", "吧", "啊", "呀", "哈", "哦", "喔", "嘛", "了", "啦", "咯",
)

_BRACKETS = (("(", ")"), ("（", "）"), ("[", "]"), ("【", "】"),
             ("“", "”"), ("「", "」"), ("《", "》"))


def looks_incomplete(text: str) -> bool:
    """这条消息看起来是不是还没说完。"""
    t = (text or "").strip()
    if not t:
        return False

    # 括号/引号没闭合
    for left, right in _BRACKETS:
        if t.count(left) > t.count(right):
            return True

    if t.endswith(_ENDINGS):
        return False

    if t.endswith(_CONTINUATIONS):
        return True

    # 很短又没有句末语气词：多半还要接着说
    if len(t) <= 12 and not any(t.endswith(e) for e in _ENDINGS):
        return True

    return False
